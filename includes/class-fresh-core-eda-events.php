/** Signed, order-ID-only online notifications for Eda. No PII and no invoice issuance in checkout. */
final class Fresh_Core_Eda_Events {
    const HOOK = 'fresh_core_eda_dispatch_order';
    public static function init(): void {
        add_action('woocommerce_new_order', array(__CLASS__, 'notify'), 20, 1);
        add_action('woocommerce_update_order', array(__CLASS__, 'notify'), 20, 1);
        add_action('woocommerce_order_status_changed', array(__CLASS__, 'notify'), 20, 1);
        add_action('woocommerce_payment_complete', array(__CLASS__, 'notify'), 20, 1);
        add_action(self::HOOK, array(__CLASS__, 'deliver'), 10, 2);
    }
    public static function enabled(): bool {
        return Fresh_Core_Accounting::enabled()
            && get_option('fresh_core_eda_events_enabled','no') === 'yes'
            && strlen((string)get_option('fresh_core_eda_events_secret','')) >= 32;
    }
    public static function notify($order_id): void {
        if (!self::enabled()) { return; }
        $order_id=absint($order_id);
        if (!$order_id || !function_exists('wc_get_order') || !wc_get_order($order_id)) { return; }
        // Merge several events generated by one Woo transaction (status + metadata updates).
        $lock='fresh_core_eda_pending_'.$order_id;
        if (get_transient($lock)) { return; }
        set_transient($lock, 1, 10);
        if (function_exists('as_enqueue_async_action')) {
            as_enqueue_async_action(self::HOOK, array($order_id, 0), 'fresh-core-eda', true);
        } else {
            wp_schedule_single_event(time()+5, self::HOOK, array($order_id, 0));
        }
    }
    public static function deliver($order_id, $attempt=0): void {
        if (!self::enabled() || !function_exists('wc_get_order')) { return; }
        $order=wc_get_order(absint($order_id));
        if (!$order || $order instanceof WC_Order_Refund) { return; }
        $url=(string)get_option('fresh_core_eda_events_url','');
        $parts=wp_parse_url($url);
        if (!$parts || ($parts['scheme']??'') !== 'https' || ($parts['host']??'') !== 'finance.freshcrackers.cz'
            || ($parts['path']??'') !== '/api/v1/shop-events' || isset($parts['query']) || isset($parts['fragment'])) { return; }
        $event_id=wp_generate_uuid4();
        $body=wp_json_encode(array('event_id'=>$event_id, 'order_id'=>(int)$order->get_id(),
            'shop_url'=>home_url('/'), 'status'=>$order->get_status(), 'occurred_at'=>gmdate('c')));
        $ts=(string)time();
        $signature=hash_hmac('sha256',$ts.'.'.$body,(string)get_option('fresh_core_eda_events_secret'));
        $response=wp_remote_post($url,array('timeout'=>25,'redirection'=>0,'blocking'=>true,'headers'=>array(
            'Content-Type'=>'application/json', 'X-Eda-Event-Timestamp'=>$ts,
            'X-Eda-Event-Signature'=>'sha256='.$signature), 'body'=>$body));
        $ok=!is_wp_error($response) && in_array((int)wp_remote_retrieve_response_code($response), array(200,202), true);
        if ($ok) { return; }
        error_log('Fresh Core Eda event delivery failed for order '.(int)$order_id.' attempt '.(int)$attempt);
        if ((int)$attempt>=4) { return; }
        $delay=min(3600, 60*(2**(int)$attempt));
        if (function_exists('as_schedule_single_action')) {
            as_schedule_single_action(time()+$delay, self::HOOK, array((int)$order_id,(int)$attempt+1), 'fresh-core-eda', true);
        } else {
            wp_schedule_single_event(time()+$delay, self::HOOK, array((int)$order_id,(int)$attempt+1));
        }
    }
}
